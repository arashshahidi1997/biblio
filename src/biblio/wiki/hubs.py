"""Generated views: hub page lists and the hub index (principle P12).

A hub lists every page that carries one of the hub's own tags. The list lives
between markers so the curated parts of the hub (scope, reading order) are
never touched.
"""
from __future__ import annotations

import os
from collections import defaultdict
from pathlib import Path

from .pages import Page, load_pages, parse_page
from .schema import WikiConfig

PAGES_START = "<!-- biblio:pages:start -->"
PAGES_END = "<!-- biblio:pages:end -->"
HUBS_START = "<!-- biblio:hubs:start -->"
HUBS_END = "<!-- biblio:hubs:end -->"
NOTICE = "<!-- generated by `biblio wiki hubs`; edits inside the markers are overwritten -->"


def link_to(cfg: WikiConfig, src: Path, page: Page, label: str | None = None) -> str:
    label = label or page.title
    if cfg.link_style == "markdown":
        rel = os.path.relpath(page.path, src.parent).replace(os.sep, "/")
        return f"[{label}]({rel})"
    return f"[[{page.name}|{label}]]" if label != page.name else f"[[{page.name}]]"


def _replace_region(text: str, start: str, end: str, content: str, heading: str) -> str:
    block = f"{start}\n{NOTICE}\n{content}{end}"
    if start in text and end in text:
        head, _, rest = text.partition(start)
        _, _, tail = rest.partition(end)
        return head + block + tail
    if heading in text:
        head, _, tail = text.partition(heading)
        return f"{head}{heading}\n\n{block}\n{tail.lstrip(chr(10))}"
    return text.rstrip("\n") + f"\n\n{heading}\n\n{block}\n"


def hub_listing(cfg: WikiConfig, hub: Page, pages: list[Page]) -> str:
    tags = set(hub.list_field("tags"))
    groups: dict[str, list[Page]] = defaultdict(list)
    for page in pages:
        if page is hub or page.type == "hub":
            continue
        if tags & set(page.list_field("tags")):
            groups[page.type or "untyped"].append(page)
    if not groups:
        return "_No pages carry this hub's tags yet._\n"
    lines = []
    for ptype in sorted(groups):
        lines.append(f"**{ptype}**\n")
        for page in sorted(groups[ptype], key=lambda p: p.title.lower()):
            status = page.status or "?"
            lines.append(f"- {link_to(cfg, hub.path, page)} ({status})")
        lines.append("")
    return "\n".join(lines)


def index_listing(cfg: WikiConfig, index_path: Path, hubs: list[Page]) -> str:
    if not hubs:
        return "_No hubs yet._\n"
    rows = []
    for hub in sorted(hubs, key=lambda p: p.title.lower()):
        tags = ", ".join(f"`{t}`" for t in hub.list_field("tags"))
        rows.append(f"- {link_to(cfg, index_path, hub)}{': ' + tags if tags else ''}")
    return "\n".join(rows) + "\n"


def expected_hub_text(cfg: WikiConfig, hub: Page, pages: list[Page]) -> str:
    return _replace_region(hub.text, PAGES_START, PAGES_END, hub_listing(cfg, hub, pages), "## Pages")


def expected_index_text(cfg: WikiConfig, index_path: Path, current: str, hubs: list[Page]) -> str:
    return _replace_region(current, HUBS_START, HUBS_END, index_listing(cfg, index_path, hubs), "## Hubs")


def stale_views(cfg: WikiConfig, pages: list[Page] | None = None) -> dict[Path, str]:
    """Return {path: expected text} for every generated view that is out of date."""
    pages = pages if pages is not None else load_pages(cfg.wiki_root)
    hubs = [p for p in pages if p.type == "hub"]
    out: dict[Path, str] = {}
    for hub in hubs:
        expected = expected_hub_text(cfg, hub, pages)
        if expected != hub.text:
            out[hub.path] = expected
    index_path = cfg.wiki_root / "index.md"
    if index_path.is_file():
        current = index_path.read_text(encoding="utf-8")
        expected = expected_index_text(cfg, index_path, current, hubs)
        if expected != current:
            out[index_path] = expected
    return out


def regenerate(cfg: WikiConfig) -> list[Path]:
    """Write all stale views; return the files written."""
    written = []
    for path, text in stale_views(cfg).items():
        path.write_text(text, encoding="utf-8")
        written.append(path)
    return written
